export function useI18n() {
    const { locale, name } = usePage<{ locale: Locale; name: string }>().props;
    const t = (k: Key) => dict[locale]?.[k] ?? dict.id[k] ?? k;
    const url = (path = '') => `/${locale}${path}`;
    return { t, locale, url, appName: name };
}
